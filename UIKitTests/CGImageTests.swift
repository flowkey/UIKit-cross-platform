import XCTest
@testable import UIKit

@MainActor
class CGImageTests: XCTestCase {
    func testDataProviderDecodesTheSourceDataInTheTexturesPixelFormat() throws {
        let twoPixelRGBAPNG: [UInt8] = [
            0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
            0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0xF4, 0x22, 0x7F,
            0x8A, 0x00, 0x00, 0x00, 0x0E, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0x00,
            0x42, 0x0D, 0x00, 0x0F, 0x7A, 0x03, 0x7E, 0x77, 0xE9, 0x7F, 0x97, 0x00, 0x00, 0x00, 0x00, 0x49,
            0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
        ]
        let image = try XCTUnwrap(CGImage(size: CGSize(width: 2, height: 1), sourceData: twoPixelRGBAPNG))

        XCTAssertEqual(image.bitsPerPixel, 32)
        XCTAssertEqual(image.bytesPerRow, 8)
        XCTAssertEqual(image.alphaInfo, .last)
        XCTAssertEqual(image.byteOrderInfo, .orderDefault)
        XCTAssertEqual(image.dataProvider?.data, [255, 0, 0, 255, 0, 0, 255, 128])
    }

    func testDataProviderIsNilWithoutSourceData() throws {
        let image = try XCTUnwrap(CGImage(size: CGSize(width: 2, height: 1)))
        XCTAssertNil(image.dataProvider)
    }
}
